"""Builds the self-contained GPU server script a remote machine runs: llama.cpp (GGUF) or vLLM behind a Cloudflare
tunnel, announced to MAZZ Control, stopping by itself after IDLE_MINUTES without request or MAX_HOURS in total."""
from __future__ import annotations

import re
from pathlib import Path
from typing import Optional

BODY = (Path(__file__).with_name("gpu_server_body.py")).read_text(encoding="utf-8")
SAFE_NAME = re.compile(r"^[A-Za-z0-9._/@+=-]{1,200}$")
BACKEND_ID = re.compile(r"^[a-z0-9][a-z0-9_-]{0,31}$")

SATURN_EPILOGUE = (
    "\n\n# Saturn: release the machine as soon as the server is done (auto_shutoff is only the backstop).\n"
    "import os as _os, urllib.request as _rq\n"
    "try:\n"
    "    _rid, _tok, _base = _os.environ.get('SATURN_RESOURCE_ID'), _os.environ.get('SATURN_TOKEN'), _os.environ.get('SATURN_BASE_URL')\n"
    "    if _rid and _tok and _base:\n"
    "        _rq.urlopen(_rq.Request(f'{_base}/api/workspaces/{_rid}/stop', method='POST', headers={'Authorization': f'token {_tok}'}), timeout=20)\n"
    "except Exception as _exc:\n"
    "    print('Arret Saturn non demande :', type(_exc).__name__)\n"
)


def served_name_for(file_or_repo: str) -> str:
    """Name seen by the Studio: lowercase, no extension, short ("Mazz-Technos-Ultra-14B.Q4_K_M.gguf" -> mazz-technos-ultra-14b-q4-k-m)."""
    base = re.sub(r"\.gguf$", "", file_or_repo.rsplit("/", 1)[-1], flags=re.I)
    return re.sub(r"[^a-z0-9]+", "-", base.lower()).strip("-")[:40] or "model"


def build_server_script(*, backend_id: str, engine: str, model: str, served_name: str, hf_repo: str, max_model_len: int = 8192,
                        idle_minutes: int = 10, max_hours: float = 0.9, hf_token: Optional[str] = None, saturn_stop: bool = False) -> str:
    """`model` is a GGUF file name inside `hf_repo` (engine llama) or a Hugging Face repo id (engine vllm)."""
    if not BACKEND_ID.match(backend_id):
        raise ValueError("backend_id invalide (minuscules, chiffres, - et _, 32 caracteres max)")
    if engine not in ("llama", "vllm"):
        raise ValueError("engine : llama ou vllm")
    for label, value in (("model", model), ("served_name", served_name), ("hf_repo", hf_repo)):
        if not SAFE_NAME.match(value or ""):
            raise ValueError(f"{label} invalide")
    if not (512 <= max_model_len <= 131072 and 1 <= idle_minutes <= 120 and 0.1 <= max_hours <= 12):
        raise ValueError("max_model_len, idle_minutes ou max_hours hors limites")
    lines = [
        "# Generated by MAZZ Control (compute/serverscript.py). Do not edit: regenerate from the Studio.",
        "import os",
        f"BACKEND_ID = {backend_id!r}", f"ENGINE = {engine!r}", f"MODEL = {model!r}", f"SERVED_NAME = {served_name!r}",
        f"HF_REPO = {hf_repo!r}", f"MAX_MODEL_LEN = {int(max_model_len)}", f"IDLE_MINUTES = {int(idle_minutes)}", f"MAX_HOURS = {float(max_hours)!r}",
    ]
    if hf_token:
        lines.append(f"os.environ['HF_TOKEN'] = {hf_token!r}")
    return "\n".join(lines) + "\n\n" + BODY + (SATURN_EPILOGUE if saturn_stop else "")
